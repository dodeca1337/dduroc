//! Прошивка пишет: схема, события, телеметрия, спаны, свободный текст.
//!
//! Сквозной пример пишущей стороны — то, что делает микросервис на приборе.
//! Запуск: `cargo run -p dduroc --example 01_device_writes`
//!
//! На диске не хранится ничего, что можно восстановить по коду прошивки:
//! ни текста, ни имён полей, ни уровней. Запись — это идентификатор типа,
//! время дельтой и бинарные поля; всё остальное подставит читатель по этой
//! же схеме (пример 02).

use dduroc::prelude::*;
use dduroc::{ChannelConfig, Durability, StorageClass};

// ---------------------------------------------------------------------------
// Схема — единственный источник правды о том, что пишет этот сервис.
//
// Макрос генерирует модуль `radio`: `radio::SCHEMA`, типы событий
// (`radio::events::PowerSet`), константы метрик (`radio::metrics::TempPa`),
// виды спанов (`radio::spans::Calibration`) и декодеры для чтения.
// ---------------------------------------------------------------------------
dduroc::schema! {
    name: radio,
    version: 1,
    // Порядок языков определяет их номера в декодерах; читатель просит язык
    // по имени ("ru"). Шаблоны хранятся в прошивке, не на диске.
    languages: [en, ru],

    events {
        // Уровень и тэги — статические свойства типа: на диск не пишутся,
        // фильтрация по ним у читателя сводится к множеству идентификаторов.
        PowerSet = 0x01 {
            level: Info,
            tags: [rf],
            en: "power set to {dbm} dBm",
            ru: "мощность {dbm} дБм",
            dbm: f32,
        },
        // `store: critical` уводит тип в критический канал: свой каталог,
        // fdatasync сразу (group commit), без сжатия, отдельная очередь,
        // у которой при переполнении вызывающий ждёт, а не теряет.
        Overheat = 0x02 {
            level: Error,
            store: critical,
            tags: [thermal],
            // В шаблоне работают format-спецификаторы Rust.
            en: "overheat: {t:.1} °C on sensor {sensor}",
            ru: "перегрев: {t:.1} °C на датчике {sensor}",
            t: f32,
            sensor: u8,
        },
        Started = 0x03 {
            level: Debug,
            en: "radio started",
            ru: "радио запущено",
        },
    }

    metrics {
        // Непрерывная величина. Пределы — range-выражения: вне `warn` —
        // тревога, вне `alarm` — авария; верхняя граница включительная.
        TempPa = 0x01 { vtype: f32, unit: "°C", tags: [thermal],
                        warn: ..=70.0, alarm: ..=85.0 },
        // Конечный автомат как временной ряд: на диск идёт только код,
        // имя состояния и его важность читатель возьмёт из схемы.
        // Коды явные: позиционная нумерация сдвинулась бы при вставке.
        LinkState = 0x02 {
            states: [Los = 0: alarm, Sync = 1: warn, Lock = 2],
            tags: [rf],
        },
        // Бинарный слепок (спектр, дамп регистров) — в канал телеметрии.
        Spectrum = 0x03 { vtype: blob, store: telemetry },
    }

    spans {
        Calibration = 0x01,
        PowerRamp = 0x02,
    }
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let root = std::env::temp_dir().join("dduroc-examples").join("01");
    let _ = std::fs::remove_dir_all(&root);

    // -----------------------------------------------------------------------
    // Хранилище. Один Store на процесс: он владеет writer-потоком и счётчиком
    // запусков. Бюджеты обязательны по смыслу: без них журнал съест носитель.
    // -----------------------------------------------------------------------
    let store = Store::open(
        StoreConfig::new(&root)
            // Сколько истории хранить у КАЖДОГО канала КАЖДОГО неймспейса.
            .with_budget(16 << 20)
            // И потолок на всё хранилище целиком: неймспейсов может быть
            // тысячи, сумма их бюджетов носителю не по карману. При
            // превышении вытесняется самый старый сегмент хранилища.
            .with_total_budget(256 << 20)
            // Политику канала можно переопределить по классу хранения.
            // Имя каталога берётся из класса, не из конфига.
            .channel(
                StorageClass::TELEMETRY,
                ChannelConfig {
                    durability: Durability::Relaxed, // sync при запечатывании
                    ..ChannelConfig::new("telemetry", 16 << 20)
                },
            ),
    )?;

    // Неймспейс — экземпляр сервиса: у "orc-radio-0" и "orc-radio-1" своя
    // история и свои каталоги, схема может быть общей.
    let ns = store.namespace("orc-radio-0", radio::SCHEMA)?;

    // -----------------------------------------------------------------------
    // События. `log` ничего не возвращает — логирование не влияет на
    // управление: с отказом на месте вызова делать нечего, а потеря учтена
    // в `store.stats().dropped` и объявлена отметкой в самом потоке записей.
    // -----------------------------------------------------------------------
    ns.log(radio::events::Started {});
    ns.log(radio::events::PowerSet { dbm: 27.5 });

    // Кому нужен вердикт на месте — парный `try_*`. Ошибки двух родов:
    // `loses_record` (диск отстаёт, запись потеряна) и `breaks_contract`
    // (тип не из этой схемы — дефект сборки).
    if let Err(e) = ns.try_log(radio::events::Overheat { t: 91.0, sensor: 1 }) {
        eprintln!("запись не прошла: {e} (потеря: {})", e.loses_record());
    }

    // -----------------------------------------------------------------------
    // Телеметрия. Ряд открывается один раз, отсчёт дальше не ищет ничего.
    // Тип значения зашит в константу метрики: `sample` у TempPa не примет
    // целое, у LinkState — состояние чужой метрики.
    // -----------------------------------------------------------------------
    let temp = ns.series(radio::metrics::TempPa)?;
    for value in [36.6, 52.0, 71.5] {
        temp.sample(value);
    }

    let link = ns.series(radio::metrics::LinkState)?;
    link.sample(radio::metrics::LinkState::Sync);
    link.sample(radio::metrics::LinkState::Lock);

    ns.series(radio::metrics::Spectrum)?
        .sample(vec![0x42u8; 512]);

    // Пределы, известные только в рантайме (модель железа определилась при
    // старте): переопределяют схемные, на диск не пишутся — это свойство
    // установки, а не измерения.
    ns.set_thresholds(radio::metrics::TempPa, ..=60.0, ..=75.0)?;

    // Движок не порождает событий сам: что делать с выходом за пределы,
    // решает приложение. Спросить важность значения можно в любой момент.
    // 65 °C по схемным пределам (warn до 70) — норма, по действующим
    // (warn до 60) — уже тревога.
    let hot = OwnedValue::F32(65.0);
    println!(
        "65.0 °C по действующим пределам: {:?} (по схемным было бы Normal)",
        ns.severity_of(radio::metrics::TempPa, &hot)
    );
    if ns.severity_of(radio::metrics::TempPa, &hot) >= Severity::Warn {
        ns.log(radio::events::Overheat { t: 65.0, sensor: 0 });
    }

    // -----------------------------------------------------------------------
    // Спаны — отрезки работы. Конец пишется при уничтожении стража, в том
    // числе при панике: незакрытый спан читатель показывает как оборванный.
    // -----------------------------------------------------------------------
    {
        let cal = ns.span(radio::spans::Calibration);
        cal.log(radio::events::PowerSet { dbm: 10.0 }); // привязано к спану

        {
            let ramp = cal.child(radio::spans::PowerRamp); // вложенность
            ns.log_in(&ramp, radio::events::PowerSet { dbm: 20.0 });
        } // конец PowerRamp — здесь

        cal.log(radio::events::PowerSet { dbm: 30.0 });
    } // конец Calibration — здесь

    // -----------------------------------------------------------------------
    // Свободный текст — для того, что не описать схемой заранее: мост из
    // tracing/log, panic-handler. Дороже событий (текст лежит на диске
    // как есть) — рабочий путь прошивки должен быть схемным.
    // -----------------------------------------------------------------------
    ns.log_text(
        Level::Warn,
        std::sync::Arc::from("app"),
        "конфигурация усилителя устарела, взят профиль по умолчанию",
        None,
    );

    // -----------------------------------------------------------------------
    // Время. Часов с батарейкой у прибора нет: у каждой записи всегда есть
    // только BootTime — номер запуска плюс микросекунды от его старта.
    // Настенное время появляется задним числом: якорь ретроактивен, одна
    // синхронизация даёт UTC всем записям этой загрузки железа — и тем,
    // что сделаны до неё.
    // -----------------------------------------------------------------------
    let early = store.now();
    println!("до синхронизации: to_utc(now) = {:?}", store.to_utc(early));

    let accepted = store.record_sync(Utc::now(), SyncSource::Ntp)?;
    println!(
        "якорь NTP принят: {accepted}; та же ранняя метка теперь: {:?}",
        store.to_utc(early)
    );
    // Менее достоверный источник не перебивает более достоверный: порядок
    // User < Ntp < Gps.
    let overwritten = store.record_sync(Utc::now(), SyncSource::User)?;
    println!("ручной ввод поверх NTP принят: {overwritten}");

    // -----------------------------------------------------------------------
    // Завершение. `sync` дожидается носителя; `shutdown` дописывает,
    // запечатывает сегменты и останавливает writer.
    // -----------------------------------------------------------------------
    ns.sync()?;

    let stats = store.stats();
    println!(
        "\nстатистика: записей {}, блоков {}, байт {}, потеряно {}, отвергнуто {}",
        stats.records_written,
        stats.blocks_written,
        stats.bytes_written,
        stats.dropped,
        stats.rejected,
    );
    assert!(
        stats.is_clean(),
        "в примере потерь быть не должно: {stats:?}"
    );

    store.shutdown();

    // Что легло на диск: по каталогу на неймспейс, внутри — по каталогу
    // на канал (классы хранения из схемы), в них сегменты `.seg`.
    println!("\nхранилище в {}:", root.display());
    print_tree(&root, 0)?;
    Ok(())
}

fn print_tree(dir: &std::path::Path, depth: usize) -> std::io::Result<()> {
    let mut entries: Vec<_> = std::fs::read_dir(dir)?.filter_map(|e| e.ok()).collect();
    entries.sort_by_key(|e| e.file_name());
    for entry in entries {
        let meta = entry.metadata()?;
        println!(
            "{:indent$}{}{}",
            "",
            entry.file_name().to_string_lossy(),
            if meta.is_dir() {
                "/".to_owned()
            } else {
                format!("  ({} Б)", meta.len())
            },
            indent = depth * 2
        );
        if meta.is_dir() {
            print_tree(&entry.path(), depth + 1)?;
        }
    }
    Ok(())
}
