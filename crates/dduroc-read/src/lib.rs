//! Чтение хранилища dduroc.
//!
//! Слой отвечает на вопрос «что произошло»: отбирает неймспейсы и каналы,
//! сливает их потоки по времени, восстанавливает то, чего нет на диске
//! (уровни, имена, шаблоны, UTC), и честно сообщает о повреждённых
//! фрагментах вместо того, чтобы выдать неполный ответ за полный.
//!
//! Работает и на устройстве, и в офлайн-вьюере, но по-разному:
//!
//! - **живой** читатель ([`Reader::of_store`], на фасаде — `store.reader()`)
//!   параллелен записи по построению: корни, схемы и якоря времени он
//!   спрашивает у хранилища на каждый запрос, а ротацию и дописываемый хвост
//!   сегмента терпит как штатные события;
//! - **дамп** ([`Reader::open_dump`]) — замороженный снимок: все корни и
//!   схемы называются разом, потому что расшифровать записи без схемы
//!   нельзя — на диске лежат только идентификаторы и бинарные поля, — а
//!   дамп без дерева какого-то класса отвергается при открытии, вместо того
//!   чтобы молча показать часть истории.
//!
//! # Время
//!
//! У записи всегда есть относительное время ([`BootTime`] — запуск плюс
//! микросекунды от его старта) и **иногда** настенное (`Entry::utc`): второе
//! появляется только там, где для загрузки железа был зафиксирован якорь
//! синхронизации. Границы запроса принимают любую из двух шкал —
//! см. [`Timestamp`].

